#!/usr/bin/env python3
"""Generate the launcher icon resources from the master SVGs in android/game/icon/.

  python3 tools/android/app_icon.py           write every output (needs: pip install resvg_py pillow)
  python3 tools/android/app_icon.py --check   verify the vector drawables match the SVGs (stdlib only)

Outputs:
  android/game/res/drawable/ic_launcher_{foreground,background}.xml   adaptive layers (API 26+);
      the foreground is also the monochrome themed layer (API 33+, only its alpha is used)
  android/game/res/mipmap-<density>/ic_launcher{,_round}.png           legacy icons (API 24-25)
  android/game/icon/play_icon_512.png                                  Google Play listing icon

The SVGs use a small subset that maps one to one onto VectorDrawable: <path> with d, fill (colour or
url(#radialGradient)) and fill-rule, <g clip-path> with a <clipPath> holding one <path>. Anything
else is rejected rather than approximated.
"""
from pathlib import Path
import argparse
import io
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[2]
ICON = ROOT / 'android/game/icon'
RES = ROOT / 'android/game/res'
SVG = '{http://www.w3.org/2000/svg}'
LAYERS = {'ic_launcher_foreground': ICON / 'ic_launcher_foreground.svg',
          'ic_launcher_background': ICON / 'ic_launcher_background.svg'}
DENSITIES = {'mdpi': 48, 'hdpi': 72, 'xhdpi': 96, 'xxhdpi': 144, 'xxxhdpi': 192}
LEGACY = [f'mipmap-{d}/ic_launcher{suffix}.png' for d in DENSITIES for suffix in ('', '_round')]


def color(value):
    value = value.strip()
    if len(value) != 7 or value[0] != '#':
        raise ValueError(f'unsupported colour {value!r}: use #RRGGBB')
    return '#FF' + value[1:].upper()


def vector(svg_path):
    """SVG subset -> VectorDrawable XML text."""
    root = ET.parse(svg_path).getroot()
    if root.get('viewBox') != '0 0 108 108':
        raise ValueError(f'{svg_path}: the viewBox must be the 108-unit adaptive layer')
    defs = {}
    for element in root.iter():
        if element.tag in (SVG + 'radialGradient', SVG + 'clipPath'):
            defs[element.get('id')] = element
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             f'<!-- Generated by tools/android/app_icon.py from android/game/icon/{svg_path.name}; do not edit. -->',
             '<vector xmlns:android="http://schemas.android.com/apk/res/android" '
             'xmlns:aapt="http://schemas.android.com/aapt"',
             '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">']

    def ref(value):
        if not value.startswith('url(#') or not value.endswith(')') or value[5:-1] not in defs:
            raise ValueError(f'{svg_path}: unresolved reference {value!r}')
        return defs[value[5:-1]]

    def path(element, indent):
        unsupported = set(element.attrib) - {'d', 'fill', 'fill-rule'}
        if unsupported:
            raise ValueError(f'{svg_path}: unsupported path attributes {sorted(unsupported)}')
        fill = element.get('fill', '')
        attrs = f'android:pathData="{element.get("d")}"'
        if element.get('fill-rule') == 'evenodd':
            attrs += ' android:fillType="evenOdd"'
        elif element.get('fill-rule') not in (None, 'nonzero'):
            raise ValueError(f'{svg_path}: unsupported fill-rule')
        if not fill.startswith('url('):
            lines.append(f'{indent}<path {attrs} android:fillColor="{color(fill)}" />')
            return
        gradient = ref(fill)
        if gradient.tag != SVG + 'radialGradient' or gradient.get('gradientUnits') != 'userSpaceOnUse':
            raise ValueError(f'{svg_path}: only userSpaceOnUse radial gradients are supported')
        lines.append(f'{indent}<path {attrs}>')
        lines.append(f'{indent}    <aapt:attr name="android:fillColor">')
        lines.append(f'{indent}        <gradient android:type="radial" android:centerX="{gradient.get("cx")}" '
                     f'android:centerY="{gradient.get("cy")}" android:gradientRadius="{gradient.get("r")}">')
        for stop in gradient.findall(SVG + 'stop'):
            lines.append(f'{indent}            <item android:offset="{stop.get("offset")}" '
                         f'android:color="{color(stop.get("stop-color"))}" />')
        lines.append(f'{indent}        </gradient>')
        lines.append(f'{indent}    </aapt:attr>')
        lines.append(f'{indent}</path>')

    for element in root:
        if element.tag == SVG + 'defs':
            continue
        if element.tag == SVG + 'path':
            path(element, '    ')
        elif element.tag == SVG + 'g' and set(element.attrib) == {'clip-path'}:
            clip = ref(element.get('clip-path')).findall(SVG + 'path')
            if len(clip) != 1 or set(clip[0].attrib) != {'d'}:
                raise ValueError(f'{svg_path}: a clipPath holds exactly one plain <path d>')
            lines.append('    <group>')
            lines.append(f'        <clip-path android:pathData="{clip[0].get("d")}" />')
            for child in element:
                if child.tag != SVG + 'path':
                    raise ValueError(f'{svg_path}: only paths inside a clipped group')
                path(child, '        ')
            lines.append('    </group>')
        else:
            raise ValueError(f'{svg_path}: unsupported element {element.tag}')
    lines.append('</vector>')
    return '\n'.join(lines) + '\n'


def render(size, shape):
    """Composite both layers, crop the 72-unit visible area and apply the legacy mask."""
    try:
        import resvg_py
        from PIL import Image, ImageDraw
    except ImportError as error:
        sys.exit(f'{error}: rendering the PNG icons needs `pip install resvg_py pillow`')
    full = round(size * 108 / 72)
    layers = [Image.open(io.BytesIO(bytes(resvg_py.svg_to_bytes(svg_string=path.read_text(), width=full,
                                                                  height=full)))).convert('RGBA')
              for path in (LAYERS['ic_launcher_background'], LAYERS['ic_launcher_foreground'])]
    image = layers[0]
    image.alpha_composite(layers[1])
    offset = (full - size) // 2
    image = image.crop((offset, offset, offset + size, offset + size))
    if shape == 'square':
        return image  # Google Play applies its own mask
    mask = Image.new('L', (size * 4, size * 4), 0)
    box = (0, 0, size * 4 - 1, size * 4 - 1)
    if shape == 'round':
        ImageDraw.Draw(mask).ellipse(box, fill=255)
    else:
        ImageDraw.Draw(mask).rounded_rectangle(box, radius=round(size * 4 * 0.18), fill=255)
    image.putalpha(mask.resize((size, size), Image.LANCZOS))
    return image


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for name, svg in LAYERS.items():
        target = RES / f'drawable/{name}.xml'
        text = vector(svg)
        if args.check:
            if not target.is_file() or target.read_text() != text:
                stale.append(str(target.relative_to(ROOT)))
        else:
            target.write_text(text)
    if args.check:
        missing = [name for name in LEGACY if not (RES / name).is_file()]
        if not (ICON / 'play_icon_512.png').is_file():
            missing.append('android/game/icon/play_icon_512.png')
        if stale or missing:
            sys.exit(f'Launcher icon outputs out of date (run tools/android/app_icon.py): stale={stale} missing={missing}')
        print('PASS launcher icon vectors match android/game/icon/*.svg; legacy and Play PNGs present')
        return
    for density, size in DENSITIES.items():
        (RES / f'mipmap-{density}').mkdir(exist_ok=True)
        render(size, 'rounded').save(RES / f'mipmap-{density}/ic_launcher.png', optimize=True)
        render(size, 'round').save(RES / f'mipmap-{density}/ic_launcher_round.png', optimize=True)
    render(512, 'square').save(ICON / 'play_icon_512.png', optimize=True)
    print('Wrote the launcher vectors, legacy mipmaps and the 512 px Play icon')


if __name__ == '__main__':
    main()
